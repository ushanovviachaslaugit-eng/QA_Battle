# 1. Запрашиваем первое число с защитой
try:
    num1 = int(input("Введите первое число: "))
    # Если дошли сюда — ошибки не было
except ValueError:
    print("Ошибка! Это не число. Завершение программы.")
    exit()  # завершаем программу

# 2. Запрашиваем второе число с защитой
try:
    num2 = int(input("Введите второе число: "))
except ValueError:
    print("Ошибка! Это не число. Завершение программы.")
    exit()

# 3. Делим и выводим результат
result = num1 / num2
print("Результат деления:", result)