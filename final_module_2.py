def get_number(prompt):
    """Эта функция просит ввести число и не отстанет, пока не получит его."""
    while True:
        try:
            # Пытаемся превратить ввод в число
            user_input = int(input(prompt))
            return user_input  # Если получилось — возвращаем число и выходим из функции
        except ValueError:
            # Если была ошибка — сообщаем и повторяем цикл
            print("ОШИБКА: Вы ввели не число! Попробуйте снова.")


def calculate(a, b, operation):
    """Выполняет математическое действие над числами a и b."""

    # 1. Сначала проверяем операцию
    if operation == "+":
        return a + b
    elif operation == "-":
        return a - b
    elif operation == "*":
        return a * b
    elif operation == "/":
        # 2. Внутри операции деления проверяем ноль
        if b == 0:
            return "Ошибка: На ноль делить нельзя!"
        else:
            return a / b
    else:
        # 3. Если пользователь ввел неизвестный символ
        return "Ошибка: Неизвестная операция. Используйте +, -, *, /."


# ----- Основная программа (здесь всё запускается) -----

print("=== КАЛЬКУЛЯТОР (с защитой от дурака) ===\n")

# 1. Получаем два числа (используем нашу умную функцию)
num1 = get_number("Введите первое число: ")
num2 = get_number("Введите второе число: ")

# 2. Получаем операцию
operation = input("Введите символ операции (+, -, *, /): ")

# 3. Отправляем данные в калькулятор и получаем результат
result = calculate(num1, num2, operation)

# 4. Выводим результат на экран
print("Результат:", result)