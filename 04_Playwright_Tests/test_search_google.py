# ============================================================
# ВЕРСИЯ 4: DUCKDUCKGO — проверка через page.content (АКТИВНА) ✅
# Что нового: проверка через содержимое страницы (не через URL)
# Это самый надёжный способ: работает с любым языком без знания кодировки
# ============================================================

# ИМПОРТ: подключаем библиотеку Playwright для управления браузером
# sync_playwright — это синхронная версия (код выполняется по очереди, как в обычной жизни)
from playwright.sync_api import sync_playwright


# ОПРЕДЕЛЕНИЕ ФУНКЦИИ: создаём функцию (рецепт) для теста
# Функция начинается с def, имя функции — test_search_duckduckgo
# pytest автоматически находит функции, которые начинаются с test_ и запускает их
def test_search_duckduckgo():
    """Автотест: поиск в DuckDuckGo и проверка результата через содержимое страницы."""

    # КОНТЕКСТНЫЙ МЕНЕДЖЕР: with ... as ... — открывает "пульт управления" Playwright
    # sync_playwright() as p — создаём объект p, через который будем запускать браузер
    # Когда код внутри with закончится, Playwright автоматически всё закроет
    with sync_playwright() as p:
        # ЗАПУСК БРАУЗЕРА: p.chromium — это движок браузера (Chrome)
        # .launch(headless=False) — запускаем браузер ВИДИМО (False = не скрытый)
        # Если поставить headless=True, браузер будет работать невидимо (для серверов)
        browser = p.chromium.launch(headless=False)

        # СОЗДАНИЕ ВКЛАДКИ: .new_page() открывает новую вкладку в браузере
        # page — это объект, через который мы управляем этой вкладкой
        page = browser.new_page()

        # ПЕРЕХОД НА САЙТ: .goto() открывает указанный URL
        # Playwright ждёт, пока страница загрузится (но не всё сразу, только основу)
        page.goto("https://duckduckgo.com")

        # ============================================================
        # ПОИСК ЭЛЕМЕНТА: используем get_by_role вместо locator
        # ============================================================
        # get_by_role("combobox") — ищем элемент, который играет роль "combobox"
        # Combobox — это поле ввода с выпадающим списком (поле поиска — именно такое)
        # Почему это лучше, чем #id или .class? Потому что роль НЕ МЕНЯЕТСЯ при обновлении сайта
        search_input = page.get_by_role("combobox")

        # ОЖИДАНИЕ ЭЛЕМЕНТА: .wait_for() ждёт, пока элемент появится на странице
        # Это важно, потому что сайт может загружать поле поиска не сразу
        # По умолчанию ждёт 30 секунд, потом падает с TimeoutError
        search_input.wait_for()

        # ============================================================
        # ВВОД ТЕКСТА: используем click() + type() вместо fill()
        # ============================================================
        # .click() — кликаем по полю, чтобы "сфокусироваться" на нём
        # Это имитирует действие пользователя: он сначала кликает в поле, потом печатает
        search_input.click()

        # .type() — вводим текст ПОСИМВОЛЬНО, как настоящий пользователь
        # "Курс доллара" — текст, который вводим
        # delay=100 — задержка 100 миллисекунд между нажатиями клавиш
        # Это важно, потому что некоторые сайты (например, Google) игнорируют fill() и ждут "живого" ввода
        search_input.type("Курс доллара", delay=100)

        # НЕБОЛЬШАЯ ПАУЗА: ждём 1 секунду, чтобы сайт обработал ввод
        # page.wait_for_timeout(1000) — пауза в миллисекундах (1000 мс = 1 секунда)
        # Это "глупая" пауза — просто стоим и ждём, ничего не проверяя
        page.wait_for_timeout(1000)

        # НАЖАТИЕ ENTER: .keyboard.press("Enter") — нажимаем клавишу Enter
        # Это запускает поиск (как будто пользователь нажал Enter после ввода)
        page.keyboard.press("Enter")

        # ОЖИДАНИЕ РЕЗУЛЬТАТОВ: ждём 3 секунды, пока загрузятся результаты поиска
        # В реальных тестах лучше использовать wait_for_selector, но здесь проще подождать
        page.wait_for_timeout(3000)

        # ============================================================
        # ПРОВЕРКА РЕЗУЛЬТАТА: получаем URL и содержимое страницы
        # ============================================================
        # .url — свойство, которое возвращает текущий URL страницы
        # Это строка типа "https://duckduckgo.com/?q=%D0%9A..."
        page_url = page.url
        print("URL страницы:", page_url)

        # .content() — метод, который возвращает ВЕСЬ HTML-код страницы
        # Возвращает строку в ОБЫЧНОМ (декодированном) виде — русские буквы читаемы
        # Это ключевой момент: мы не работаем с URL-кодировкой, а видим текст как есть
        page_content = page.content()

        # ASSERT (УТВЕРЖДЕНИЕ): проверяем, что слово "доллар" есть на странице
        # "доллар" in page_content.lower() — проверяет, содержит ли текст страницы "доллар"
        # .lower() — приводит всё к нижнему регистру (чтобы "Доллар" и "доллар" совпадали)
        # Если слово НЕ найдено — программа падает с AssertionError и сообщением
        assert "доллар" in page_content.lower(), "Слово 'доллар' не найдено на странице результатов"

        # Если мы дошли до этой строчки — значит, assert прошёл успешно
        print("✅ Тест пройден! На странице есть результаты по запросу 'доллар'.")

        # ЗАКРЫТИЕ БРАУЗЕРА: .close() закрывает браузер и освобождает ресурсы
        browser.close()


# УСЛОВИЕ ЗАПУСКА: этот блок выполняется, только если файл запущен как скрипт
# __name__ == "__main__" — это стандартная проверка Python
# Если файл импортирован в другой файл — этот блок НЕ выполнится
# Если файл запущен напрямую (Run) — блок ВЫПОЛНИТСЯ
if __name__ == "__main__":
    test_search_duckduckgo()